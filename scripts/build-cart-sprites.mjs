// Bake code-native artwork onto a fixed grid. No smoothing or extra colors.
import {build} from 'esbuild';
import {writeFile,rm} from 'node:fs/promises';
import {renderToStaticMarkup} from 'react-dom/server';
import {createElement} from 'react';
const root=new URL('../',import.meta.url);
const temporary=new URL('./.cart-artwork.mjs',import.meta.url);
await build({entryPoints:[new URL('src/CartArtwork.tsx',root).pathname],outfile:temporary.pathname,bundle:true,platform:'node',format:'esm',packages:'external',jsx:'automatic'});
try {
 const {GolfCart}=await import(temporary.href+'?build='+Date.now());
 const sprites=[];
 for(let direction=0;direction<8;direction++)for(let wheelStep=0;wheelStep<2;wheelStep++){
  const svg=renderToStaticMarkup(createElement(GolfCart,{direction,wheelStep}));
  const grid=Array.from({length:28},()=>Array(28).fill(null));
  for(const tag of svg.matchAll(/<(polygon|line|path)\b([^>]+)>/g)){
   const a=Object.fromEntries([...tag[2].matchAll(/([\w-]+)="([^"]*)"/g)].map(m=>[m[1],m[2]]));
   let points;
   if(tag[1]==='polygon')points=a.points.split(' ').map(p=>p.split(',').map(Number));
   if(tag[1]==='path'){
    const m=a.d.match(/^M([-\d.]+) ([-\d.]+)h([-\d.]+)v([-\d.]+)h/);
    if(!m)throw Error('Unsupported sprite path: '+a.d);
    const [x,y,w,h]=m.slice(1).map(Number);points=[[x,y],[x+w,y],[x+w,y+h],[x,y+h]];
   }
   const palette={'#fff0ca':'#fff0cb','#fff1c9':'#fff0cb','#f5e5bd':'#e7d9af','#c7b78c':'#cbb990','#bfb58e':'#cbb990','#75674d':'#52654a','#354b3b':'#344c3a','#4b6049':'#52654a','#3a5542':'#344c3a','#354c3c':'#344c3a','#294635':'#344c3a','#b3c0a0':'#b0b69a','#bfccb8':'#b0b69a','#8e5c42':'#995139'};
   const raw=a.fill??a.stroke;
   const color=(palette[raw]??raw)+'|'+(a.opacity??'1');
   for(let row=0;row<28;row++)for(let col=0;col<28;col++){
    const x=col*2.5-33.75,y=row*2.5-43.75;let hit=false;
    if(points){for(let i=0,j=points.length-1;i<points.length;j=i++){
      const [ax,ay]=points[i],[bx,by]=points[j];
      if((ay>y)!==(by>y)&&x<(bx-ax)*(y-ay)/(by-ay)+ax)hit=!hit;
    }}else{
     const ax=+a.x1,ay=+a.y1,dx=+a.x2-ax,dy=+a.y2-ay;
     const t=Math.max(0,Math.min(1,((x-ax)*dx+(y-ay)*dy)/(dx*dx+dy*dy||1)));
     hit=Math.hypot(x-ax-t*dx,y-ay-t*dy)<=Math.max(1.25,+a['stroke-width']/2);
    }
    if(hit)grid[row][col]=color;
   }
  }
  const groups=new Map();
  for(let y=0;y<28;y++)for(let x=0;x<28;){
   const color=grid[y][x];if(!color){x++;continue;}
   let end=x+1;while(end<28&&grid[y][end]===color)end++;
   groups.set(color,(groups.get(color)??'')+`M${x} ${y}h${end-x}v1H${x}z`);x=end;
  }
  sprites.push([...groups].map(([color,d])=>{const [fill,opacity]=color.split('|');return {fill,opacity:+opacity,d};}));
 }
 await writeFile(new URL('src/cartSprites.ts',root),'// Generated by scripts/build-cart-sprites.mjs; each cell is one sprite pixel.\nexport const cartSprites = '+JSON.stringify(sprites)+';\n');
}finally{await rm(temporary,{force:true});}
